#!/usr/bin/env python3
"""Compile agents/voice-aqe-quant.md from the aqe-quant card + canon lock, using the elder-lens agent as the shared-machinery template
(sections 3-6: process, memory, output, forbidden are identical for every seat). Report C only. Re-run after editing the card or the lock."""
import json, os, re, sys, yaml
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
tmpl = open(os.path.join(ROOT, "agents/voice-elder-lens.md")).read()
card = open(os.path.join(ROOT, "skills/voice-aqe-quant/SKILL.md")).read().split("---", 2)[2].strip()
lock = yaml.safe_load(open(os.path.join(ROOT, "canon/aqe-quant/canon.lock.yaml")))
menu = json.load(open(os.path.join(ROOT, "..", "aegis-core/skills/pma/contracts/voice_menus.json")))["aqe-quant"]
head = tmpl.split("# AGENT: VOICE-ELDER-LENS")[0]
head = head.replace("name: voice-elder-lens", "name: voice-aqe-quant").replace("elder-lens", "aqe-quant")
floor_idx = card.index("## 7 · ON THE FLOOR")
main_card, floor = card[:floor_idx].rstrip(), card[floor_idx:].strip()
canon = ["## 1b · MY CANON (house doctrine from the AQE Technical Reference; NOT SEALED -- pending PM sign-off)",
         "The text I am pinned to:", "  · **AQETR** = *AQE Technical Reference* (this repository) -- foundational", "",
         "I cite a canon id (e.g. `A3`) in my `checklist_trace` for every checklist step I walk. All principles are labelled HOUSE; none is cited to an outside book.", ""]
canon += [f"- **{p['id']}** -- {' '.join(p['text'].split())}" for p in lock["principles"]]
rec = ["", "## 1c · MY RECOGNISERS (tests against the fields I have)",
       "The IF side is data, never impression. A recogniser whose field is missing is a disclosure, never a pass.", ""]
rec += [f"- **{r['id']}** -- IF {r['if']}  ->  THEN {' '.join(r['then'].split())}" for r in lock["recognisers"]]
tax = ["", "## 2 · MY DATA TAXONOMY (the ONLY fields I read -- my data menu, enforced)", ", ".join(f"`{m}`" for m in menu),
       "Reading any field not on this menu is a breach the auditor checks. Every field is explained in the AQE glossary below; if a meaning is unclear I say so and do not invent analysis over it.", "",
       "## 2b · THE AQE GLOSSARY (plain words; contracts/aqe_glossary.md -- injected into my packet, never optional)"]
glossary_path = os.path.join(ROOT, "..", "aegis-core/skills/pma/contracts/aqe_glossary.md")
tax.append(open(glossary_path).read().split("\n", 1)[1].strip() if os.path.exists(glossary_path) else "(glossary missing -- build it with tools/aqe_glossary.py)")
mid = tmpl.index("## 3 · MY PROCESS")
tail = tmpl[mid:]
tail = tail.split("## 7 · ON THE FLOOR")[0].rstrip()
tail = re.sub(r"# RESERVE BENCH:.*?\n\n(?=## 4)", "", tail, flags=re.S)
tail = tail.replace("elder-lens", "aqe-quant")
tail = tail.replace("\"reason\":\"First orderly pullback after a momentum thrust; contraction tightening; risk defined at 56.1\",\"fields_cited\":[\"elder_5d\",\"vcp_tightness_pct\",\"bracket.stop\"]",
                    "\"reason\":\"Support is broad (flow, energy, structure, mp all above 60) and the exhaustion test is clean\",\"fields_cited\":[\"energy\",\"structure\",\"subcomponents.energy.exhaustion_score\"]")
tail = tail.replace('"elder_5d"', '"structure"').replace('"bracket.stop"', '"subcomponents.energy.exhaustion_score"').replace('"mp_accel_state"', '"mp_accel_state"')
out = (head + "# AGENT: VOICE-AQE-QUANT -- complete standalone instruction set (GENERATED by tools/compile_aqe_quant_agent.py; edit the card, not this)\n\n"
       "## 1 · WHO I AM (identity, looks-for, checklist, data menu)\n" + main_card + "\n\n" + "\n".join(canon) + "\n" + "\n".join(rec) + "\n"
       + "\n".join(tax) + "\n\n" + tail + "\n\n" + floor + "\n")
out = out.replace('"fields_cited": [\n    "elder_5d",\n    "bracket.stop"\n   ]', '"fields_cited": [\n    "structure",\n    "subcomponents.energy.exhaustion_score"\n   ]')
dst = os.path.join(ROOT, "agents/voice-aqe-quant.md")
open(dst, "w").write(out)
print("wrote", os.path.relpath(dst, ROOT), len(out.splitlines()), "lines")
