#!/usr/bin/env python3
"""ONE CODE TREE (BUILD_PLAN Phase 1, PM 2026-10-30): aegis/plugin/ is the truth.

The nightly AQE run reads a few plugin files at fixed runtime paths that must
NOT move (src/pipeline/voice_packets.py imports pma_pipeline.py by path, and
.github/workflows/deploy-hf.yml re-adds exactly those paths into the HF
mirror). So those paths are GENERATED copies of the plugin files, produced by
this script, and tests/test_one_code_tree.py fails the suite if they drift.

Run after any edit under aegis/plugin/:
    python3 aegis/plugin/sync_runtime.py          # copy + write GENERATED.json
    python3 aegis/plugin/sync_runtime.py --check  # exit 1 on drift, change nothing

Direction is plugin -> runtime, never the reverse. Edit the plugin file.
"""
from __future__ import annotations

import hashlib
import json
import os
import shutil
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent          # aegis/plugin
AEGIS = HERE.parent                              # aegis
ROOT = AEGIS.parent                              # repo root

CORE = HERE / "aegis-core"
VOICES = HERE / "aegis-voices"

# (source in the plugin tree) -> (generated runtime path), both repo-relative.
PAIRS: list[tuple[Path, Path]] = [
    (CORE / "skills/pma/tools/pma_pipeline.py",
     AEGIS / "skills/premarket-analysis/tools/pma_pipeline.py"),
    # 2026-11-03: src/pipeline/committee_data.py builds the weekly / daily / 1-hour grid in the nightly job.
    (CORE / "skills/pma/tools/mtf.py",
     AEGIS / "skills/premarket-analysis/tools/mtf.py"),
    (CORE / "skills/pma/contracts/voice_menus.json",
     AEGIS / "skills/premarket-analysis/contracts/voice_menus.json"),
]
# Every voice canon lock the plugin ships is mirrored under aegis/canon/<voice>/.
for lock in sorted((VOICES / "canon").glob("*/canon.lock.yaml")):
    PAIRS.append((lock, AEGIS / "canon" / lock.parent.name / "canon.lock.yaml"))

MANIFEST = AEGIS / "skills/premarket-analysis/GENERATED.json"


def _sha(p: Path) -> str:
    return hashlib.sha256(p.read_bytes()).hexdigest()


def _rel(p: Path) -> str:
    return p.relative_to(ROOT).as_posix()


def _versions() -> dict:
    out = {}
    for plug in ("aegis-core", "aegis-voices"):
        pj = HERE / plug / ".claude-plugin" / "plugin.json"
        out[plug] = json.loads(pj.read_text(encoding="utf-8")).get("version")
    return out


def check() -> list[str]:
    """Return a list of human-readable drift problems (empty = clean)."""
    problems: list[str] = []
    for src, dst in PAIRS:
        if not src.exists():
            problems.append(f"plugin source missing: {_rel(src)}")
            continue
        if not dst.exists():
            problems.append(f"generated copy missing: {_rel(dst)} (run sync_runtime.py)")
            continue
        if _sha(src) != _sha(dst):
            problems.append(f"DRIFT: {_rel(dst)} != {_rel(src)} (edit the plugin file, then run sync_runtime.py)")
    if not MANIFEST.exists():
        problems.append(f"manifest missing: {_rel(MANIFEST)}")
    else:
        man = json.loads(MANIFEST.read_text(encoding="utf-8"))
        if man.get("plugin_versions") != _versions():
            problems.append(f"manifest plugin_versions {man.get('plugin_versions')} != plugin.json {_versions()}")
        recorded = {e["generated"]: e["sha256"] for e in man.get("files", [])}
        for src, dst in PAIRS:
            if dst.exists() and recorded.get(_rel(dst)) != _sha(dst):
                problems.append(f"manifest sha stale for {_rel(dst)}")
    return problems


def sync() -> None:
    files = []
    for src, dst in PAIRS:
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(src, dst)
        files.append({"source": _rel(src), "generated": _rel(dst), "sha256": _sha(dst)})
    MANIFEST.write_text(json.dumps({
        "_note": ("GENERATED by aegis/plugin/sync_runtime.py from aegis/plugin/ (the one code tree). "
                  "Do not edit the generated files; edit the plugin source and re-run the script. "
                  "tests/test_one_code_tree.py enforces this."),
        "plugin_versions": _versions(),
        "files": files,
    }, indent=1) + "\n", encoding="utf-8")
    print(f"synced {len(files)} files; manifest -> {_rel(MANIFEST)}")


if __name__ == "__main__":
    if "--check" in sys.argv:
        probs = check()
        for p in probs:
            print(p)
        print("one-code-tree: " + ("CLEAN" if not probs else f"{len(probs)} problem(s)"))
        sys.exit(1 if probs else 0)
    sync()
